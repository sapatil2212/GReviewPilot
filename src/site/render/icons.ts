export const ICON_NAMES: string[] = Object.keys(SITE_ICONS).sort();

/**
 * Look up an icon, tolerating the casing and naming variations the AI and
 * users produce ("map-pin", "mappin", "MapPin").
 */
export function resolveIcon(name?: string | null): LucideIcon {
  if (!name) return Sparkles;
  if (SITE_ICONS[name]) return SITE_ICONS[name];
  const normalized = name.replace(/[^a-z0-9]/gi, "").toLowerCase();
  const match = ICON_NAMES.find((n) => n.toLowerCase() === normalized);
  return match ? SITE_ICONS[match] : Sparkles;
}

